#!/usr/bin/env python3
"""Create a least-privilege Kaltura role and an AppToken bound to it."""

from __future__ import annotations

import argparse
import getpass
import json
import os
import re
import ssl
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any


DEFAULT_SERVICE_URL = "https://www.kaltura.com/api_v3"
DEFAULT_SESSION_DURATION = 900
DEFAULT_ADMIN_KS_DURATION = 300


class KalturaError(RuntimeError):
    """A Kaltura API or transport error."""


def api_post(service_url: str, service: str, action: str, data: dict[str, Any]) -> Any:
    url = f"{service_url.rstrip('/')}/service/{service}/action/{action}"
    payload = {"format": 1, **data}
    request = urllib.request.Request(
        url,
        data=urllib.parse.urlencode(payload).encode("utf-8"),
        headers={"Content-Type": "application/x-www-form-urlencoded"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=30, context=ssl.create_default_context()) as response:
            body = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise KalturaError(f"HTTP {exc.code} from {service}.{action}: {detail}") from exc
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
        raise KalturaError(f"Request to {service}.{action} failed: {exc}") from exc

    result = body.get("result", body) if isinstance(body, dict) else body
    error = result.get("error", result) if isinstance(result, dict) else None
    if isinstance(error, dict) and (error.get("code") or error.get("message")):
        code = error.get("code", "KALTURA_ERROR")
        message = error.get("message", "Unknown Kaltura API error")
        raise KalturaError(f"{service}.{action}: {code}: {message}")
    return result


def normalize_permissions(raw: str) -> list[str]:
    values = [item.strip() for item in re.split(r"[\s,]+", raw) if item.strip()]
    invalid = [item for item in values if not re.fullmatch(r"[A-Z][A-Z0-9_]*", item)]
    if invalid:
        raise ValueError(f"Invalid permission name(s): {', '.join(invalid)}")
    return list(dict.fromkeys(values))


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug or "kaltura-app"


def prompt_value(label: str, default: str | None = None) -> str:
    suffix = f" [{default}]" if default else ""
    value = input(f"{label}{suffix}: ").strip()
    return value or (default or "")


def write_credentials(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    descriptor = os.open(path, flags, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("# Generated by create_scoped_app_token.py; do not commit.\n")
            for key, value in values.items():
                handle.write(f"{key}={value}\n")
    except Exception:
        try:
            path.unlink()
        except OSError:
            pass
        raise


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a Kaltura role and a SHA-256 AppToken scoped to that role."
    )
    parser.add_argument("--partner-id", help="Kaltura partner ID; prompted if omitted")
    parser.add_argument("--role-name", help="Name for the new Kaltura role; prompted if omitted")
    parser.add_argument(
        "--permissions",
        help="Comma- or whitespace-separated Kaltura permission names; prompted if omitted",
    )
    parser.add_argument(
        "--permissions-file",
        type=Path,
        help="Text file containing comma- or whitespace-separated permission names",
    )
    parser.add_argument("--description", help="Role and AppToken description")
    parser.add_argument("--user-id", help="Fixed audit user ID for sessions minted by the token")
    parser.add_argument(
        "--session-type",
        choices=("user", "admin"),
        default="admin",
        help="Scoped KS type (default: admin for server-side automation)",
    )
    parser.add_argument(
        "--session-duration",
        type=int,
        default=DEFAULT_SESSION_DURATION,
        help=f"Maximum scoped KS lifetime in seconds (default: {DEFAULT_SESSION_DURATION})",
    )
    parser.add_argument(
        "--extra-privilege",
        action="append",
        default=[],
        help="Additional immutable KS privilege, such as list:* (repeatable)",
    )
    parser.add_argument("--service-url", default=DEFAULT_SERVICE_URL)
    parser.add_argument("--output", type=Path, help="Credential output file")
    parser.add_argument("--yes", action="store_true", help="Skip the final interactive confirmation")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.session_duration < 60:
        raise ValueError("Session duration must be at least 60 seconds")

    partner_raw = args.partner_id or prompt_value("Kaltura partner ID")
    if not partner_raw.isdigit() or int(partner_raw) <= 0:
        raise ValueError("Partner ID must be a positive integer")
    partner_id = int(partner_raw)

    role_name = args.role_name or prompt_value("New role name")
    if not role_name:
        raise ValueError("Role name is required")
    if args.permissions and args.permissions_file:
        raise ValueError("Use either --permissions or --permissions-file, not both")
    if args.permissions_file:
        try:
            permission_raw = "\n".join(
                line.split("#", 1)[0]
                for line in args.permissions_file.read_text(encoding="utf-8").splitlines()
            )
        except OSError as exc:
            raise ValueError(f"Could not read permissions file: {exc}") from exc
    else:
        permission_raw = args.permissions or prompt_value(
            "Required permission names (comma-separated)"
        )
    permissions = normalize_permissions(permission_raw)
    if not permissions:
        raise ValueError("At least one permission is required")

    slug = slugify(role_name)
    description = args.description or f"Least-privilege AppToken for {role_name}"
    user_id = args.user_id or f"app-token-{slug}"
    output = args.output or Path("credentials") / f"{slug}.env"
    if output.exists():
        raise FileExistsError(f"Credential file already exists: {output}")

    session_type = 2 if args.session_type == "admin" else 0
    privileges = [f"setrole:ROLE_ID", *args.extra_privilege]
    print("\nProvisioning plan")
    print(f"  Partner ID:       {partner_id}")
    print(f"  Role:             {role_name}")
    print(f"  Permissions:      {', '.join(permissions)}")
    print(f"  Session type:     {args.session_type.upper()}")
    print(f"  Session duration: {args.session_duration} seconds")
    print(f"  Session user ID:  {user_id}")
    print(f"  Privileges:       {', '.join(privileges)}")
    print(f"  Credential file:  {output}")

    if not args.yes and input("\nCreate this role and AppToken? [y/N]: ").strip().lower() not in {"y", "yes"}:
        print("No changes made.")
        return 0

    admin_secret = getpass.getpass("Kaltura admin secret (input hidden): ")
    if not admin_secret:
        raise ValueError("Admin secret is required")

    admin_ks = api_post(
        args.service_url,
        "session",
        "start",
        {
            "partnerId": partner_id,
            "secret": admin_secret,
            "userId": "app-token-bootstrap",
            "type": 2,
            "expiry": DEFAULT_ADMIN_KS_DURATION,
        },
    )
    if isinstance(admin_ks, dict):
        admin_ks = admin_ks.get("ks")
    if not isinstance(admin_ks, str) or not admin_ks:
        raise KalturaError("session.start did not return a KS")

    role = api_post(
        args.service_url,
        "userRole",
        "add",
        {
            "ks": admin_ks,
            "userRole[objectType]": "KalturaUserRole",
            "userRole[name]": role_name,
            "userRole[description]": description,
            "userRole[permissionNames]": ",".join(permissions),
            "userRole[tags]": "app-token,least-privilege",
        },
    )
    role_id = role.get("id") if isinstance(role, dict) else None
    if role_id is None:
        raise KalturaError("userRole.add succeeded without returning a role ID")

    final_privileges = [f"setrole:{role_id}", *args.extra_privilege]
    try:
        token = api_post(
            args.service_url,
            "appToken",
            "add",
            {
                "ks": admin_ks,
                "appToken[objectType]": "KalturaAppToken",
                "appToken[hashType]": "SHA256",
                "appToken[sessionType]": session_type,
                "appToken[sessionDuration]": args.session_duration,
                "appToken[sessionPrivileges]": ",".join(final_privileges),
                "appToken[sessionUserId]": user_id,
                "appToken[description]": description,
            },
        )
    except Exception as exc:
        raise KalturaError(
            f"Role {role_id} was created, but AppToken creation failed. "
            f"Review or delete that role in Kaltura. Cause: {exc}"
        ) from exc

    token_id = token.get("id") if isinstance(token, dict) else None
    token_value = token.get("token") if isinstance(token, dict) else None
    if not token_id or not token_value:
        raise KalturaError(
            f"AppToken was created for role {role_id}, but its ID or secret was absent from the response"
        )

    write_credentials(
        output,
        {
            "KALTURA_PARTNER_ID": str(partner_id),
            "KALTURA_SERVICE_URL": args.service_url.rstrip("/"),
            "KALTURA_APP_TOKEN_ID": str(token_id),
            "KALTURA_APP_TOKEN_VALUE": str(token_value),
            "KALTURA_APP_TOKEN_HASH_TYPE": "SHA256",
            "KALTURA_APP_TOKEN_SESSION_TYPE": str(session_type),
            "KALTURA_APP_TOKEN_SESSION_DURATION": str(args.session_duration),
            "KALTURA_APP_TOKEN_USER_ID": user_id,
            "KALTURA_ROLE_ID": str(role_id),
            "KALTURA_ROLE_PERMISSIONS": ",".join(permissions),
        },
    )
    print(f"\nCreated role {role_id} and AppToken {token_id}.")
    print(f"Credentials saved to {output}. The admin secret was not saved.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (KalturaError, ValueError, FileExistsError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(1)
